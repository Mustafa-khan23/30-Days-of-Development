//operators in JavaScript :
let num1 = 10;
let num2 = 5;

//1. Arithmetic operator
const sum = num1 + num2;
const sub = num1 - num2;
const mul = num1 * num2;
const div = num1 / num2;
const pow = Math.pow(2, 5); //25

//----------------------------------------------------------------------

//2. relational operator
const isEqual = num1 == num2;
const isDiff = num1 === num2;
const isGreater = num1 > num2;
const isSmaller = num1 < num2;
const isGreaterEq = num1 >= num2;
const isSmallerEq = num1 <= num2;

//----------------------------------------------------------------------

//3. Logical operator
const AND = num1 && num2;
const OR = num1 || num2;
const NOT = !num1;

//----------------------------------------------------------------------

//4. Unary Operator
const increment = num1++; //increment
const decrement = num1--; //decrement

//----------------------------------------------------------------------

//5. Ternary Operator
const result = "condition" ? true : false;

//----------------------------------------------------------------------